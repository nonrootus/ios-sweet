#!/usr/bin/env python3
"""Reproduce A618 powerup-list offsets from SHA-pinned Xiaomi10c33d40 sources.
No hardware access; offsets are GPU-relative DWORD indices, not addresses.
"""
import argparse,hashlib,re
from pathlib import Path
PINNED={
 'adreno_a6xx.c':'349f7702e22e2e00dd38097703392ee7094ba0a04697fd5ec6625f25754eea19',
 'a6xx_reg.h':'5745812e30f49a00268f3d95c8d089ef860391613d9084b79f5b17cd9ac0846b',
 'adreno_a6xx.h':'a95df1c416ec6f299ff310c1565dfe32102400ade0b99f247d6fe2fe1e8921f6',
 'adreno-gpulist.h':'d1cd30a8bab738498b2d3eda6a9e38aa626b343206bbf1a04af280ede782255c',
}
LISTS=('a6xx_ifpc_pwrup_reglist','a6xx_pwrup_reglist','a615_pwrup_reglist')
def profile(stock):
    contents={}
    for name,digest in PINNED.items():
        data=(stock/name).read_bytes()
        if hashlib.sha256(data).hexdigest()!=digest:raise ValueError('Unrecognized source: '+name)
        contents[name]=data.decode('utf-8')
    source=contents['adreno_a6xx.c'];regs=contents['a6xx_reg.h'];groups=[]
    for name in LISTS:
        body=re.search(r'\b'+name+r'\[\] = \{(.*?)\n\};',source,re.S)
        if not body:raise ValueError('Missing list: '+name)
        expressions=re.findall(r'\{\s*(A6XX_\w+(?:\+\d+)?)\s*,\s*0x0\s*\}',body[1])
        if len(expressions)!=body[1].count('{'):raise ValueError('Unsupported register entry')
        entries=[]
        for expr in expressions:
            symbol,_,extra=expr.partition('+')
            defs=re.findall(r'^#define\s+'+symbol+r'\s+(0x[0-9a-fA-F]+|\d+)\s*$',regs,re.M)
            if len(defs)!=1:raise ValueError('Unsupported register definition: '+symbol)
            entries.append((expr,int(defs[0],0)+(int(extra) if extra else 0)))
        groups.append(entries)
    if list(map(len,groups))!=[38,28,1]:raise ValueError('Unexpected stock list geometry')
    device=re.search(r'\.gpurev = ADRENO_REV_A618,(.*?)\n\s*\},',contents['adreno-gpulist.h'],re.S)
    if not device or 'ADRENO_PERFCTRL_RETAIN' in device[1]:raise ValueError('Unsupported A618 feature profile')
    layout=re.search(r'struct cpu_gpu_lock \{(.*?)\n\};',contents['adreno_a6xx.h'],re.S)
    if not layout or re.findall(r'(uint\d+_t)\s+(\w+);',layout[1])!=[
        ('uint32_t','flag_ucode'),('uint32_t','flag_kmd'),('uint32_t','turn'),('uint16_t','list_length'),('uint16_t','list_offset')]:
        raise ValueError('Unsupported spinlock layout')
    return groups,contents
def header(groups):
    rows=[entry for group in groups for entry in group]
    lines=['/* Generated by tools/import-a618-pwrup-profile.py from Xiaomi10c33d40.',
           ' * GPU-relative DWORD indices. This file neither reads nor writes MMIO. */',
           '#ifndef SWEET_A618_PWRUP_PROFILE_H','#define SWEET_A618_PWRUP_PROFILE_H',
           'static const uint32_t sweet_a618_pwrup_offsets[67] = {']
    lines += [f'    0x{value:05x}u, /* {name} */' for name,value in rows]
    return '\n'.join(lines+['};','#endif',''])
def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('stock',type=Path);p.add_argument('output',type=Path);args=p.parse_args()
    groups,_=profile(args.stock);args.output.write_bytes(header(groups).encode())
    print('Imported67 stock offsets, IFPC38 + shared28 + A615extra1; no hardware access')
if __name__=='__main__':main()
