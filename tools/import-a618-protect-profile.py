#!/usr/bin/env python3
"""Reproduce the A618 CP register-protection values from stock source and FDT."""
import argparse
import hashlib
import importlib.util
import re
from pathlib import Path

STOCK = {
    'adreno_a6xx.c': '349f7702e22e2e00dd38097703392ee7094ba0a04697fd5ec6625f25754eea19',
    'a6xx_reg.h': '5745812e30f49a00268f3d95c8d089ef860391613d9084b79f5b17cd9ac0846b',
    'adreno-gpulist.h': 'd1cd30a8bab738498b2d3eda6a9e38aa626b343206bbf1a04af280ede782255c',
}
FDT_SHA256 = '6378a14e6e3e18c04975c9516e5f482f763d6e3e7d062ce467d1130ef5821c02'
spec = importlib.util.spec_from_file_location('fdt', Path(__file__).with_name('gpu-dt-info.py'))
fdt = importlib.util.module_from_spec(spec)
spec.loader.exec_module(fdt)


def checked(path, expected):
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != expected:
        raise ValueError('Unexpected input hash: ' + path.name)
    return data


def generate(stock, live_fdt):
    source = {name: checked(stock / name, sha).decode() for name, sha in STOCK.items()}
    gpu = re.search(r'\.gpurev = ADRENO_REV_A618,(.*?)\n\s*\},', source['adreno-gpulist.h'], re.S)
    if not gpu or not re.search(r'\.num_protected_regs\s*=\s*0x20\b', gpu[1]):
        raise ValueError('Unexpected A618 protection capacity')
    group = re.search(r'\ba6xx_protected_regs_group\[\] = \{(.*?)\n\};', source['adreno_a6xx.c'], re.S)
    rows = re.findall(r'\{\s*(0x[0-9a-fA-F]+),\s*(0x[0-9a-fA-F]+),\s*([01])\s*\}', group[1]) if group else []
    if len(rows) != 28 or len(rows) != group[1].count('{'):
        raise ValueError('Unexpected fixed stock register groups')
    entries = [(int(base,16),int(count,16),int(read)) for base,count,read in rows]
    nodes = fdt.parse_fdt(checked(live_fdt, FDT_SHA256))
    if fdt.cells(nodes['/soc/qcom,kgsl-3d0@5000000']['qcom,chipid']) != [0x06010800]:
        raise ValueError('Unexpected GPU chip ID')
    mmu = nodes['/soc/qcom,kgsl-iommu@5040000']
    base, span = fdt.cells(mmu['qcom,protect'])
    if (base, span) != (0x40000, 0x10000):
        raise ValueError('Unexpected SMMU protection range')
    first, remaining = base // 4, span // 4
    while remaining:
        count = min(remaining, 0x2000)
        entries.append((first, count - 1, 1))
        first += count
        remaining -= count
    if any(base + count >= 1 << 18 or count >= 1 << 13 for base, count, _ in entries):
        raise ValueError('Register protection field overflow')
    if len(entries) != 30:
        raise ValueError('Unexpected protection group total')
    def reg(name):
        match = re.search(r'^#define\s+'+name+r'\s+(0x[\da-fA-F]+)\s*$', source['a6xx_reg.h'], re.M)
        if not match:
            raise ValueError('Missing ' + name)
        return int(match[1], 16)
    control, first_slot = reg('A6XX_CP_PROTECT_CNTL'), reg('A6XX_CP_PROTECT_REG')
    lines = ['/* Generated by tools/import-a618-protect-profile.py from Xiaomi10c33d40',
             ' * and the captured sweet_k6a FDT. Register offsets are DWORDs. */',
             '#ifndef SWEET_A618_PROTECT_PROFILE_H', '#define SWEET_A618_PROTECT_PROFILE_H',
             '#include <stdint.h>', f'#define SWEET_A618_PROTECT_CONTROL 0x{control:x}u',
             f'#define SWEET_A618_PROTECT_FIRST_SLOT 0x{first_slot:x}u',
             '#define SWEET_A618_PROTECT_ENABLE 3u', '#define SWEET_A618_PROTECT_SLOTS 32u',
             '#define SWEET_A618_PROTECT_COUNT 30u',
             'static const uint32_t sweet_a618_protect_values[SWEET_A618_PROTECT_COUNT] = {']
    for index, (base, count, read) in enumerate(entries):
        value = base | (count << 18) | (read << 31)
        lines.append(f'    0x{value:08x}u, /* slot {index}: 0x{base:05x}-0x{base+count:05x} */')
    return '\n'.join(lines + ['};', '#endif', '']).encode()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('stock', type=Path)
    parser.add_argument('live_fdt', type=Path)
    parser.add_argument('header', type=Path)
    args = parser.parse_args()
    args.header.write_bytes(generate(args.stock, args.live_fdt))
    print('Imported 28 stock GPU groups and 2 captured SMMU groups')


if __name__ == '__main__':
    main()
